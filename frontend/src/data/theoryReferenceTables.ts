export function theoryTableSearchBlob(table: TheoryRefTable): string {
  return [
    table.title,
    table.note ?? '',
    table.headers.join(' '),
    table.rows.map((r) => r.join(' ')).join(' '),
    table.tags.join(' '),
  ].join('\n')
}
